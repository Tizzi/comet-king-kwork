export function groupTitle(id: string) {
  return GROUPS.find((g) => g.id === id)?.title ?? "Прочее";
}

export function classifyPart(name: string, note = "") {
  const text = `${name} ${note}`.toLowerCase().replace(/ё/g, "е");
  for (const [id, keys] of RULES) {
    if (keys.some((key) => text.includes(key))) return id;
  }
  return "other";
}
