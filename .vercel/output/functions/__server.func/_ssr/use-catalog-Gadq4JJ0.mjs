var cache = null;
function unpackPhoto(hosts, token) {
	const match = token.match(/^(\d+)(\/.*)$/);
	if (!match) return token;
	const host = hosts[Number(match[1])];
	return host ? host + match[2] : token;
}
function loadSeed() {
	if (!cache) {
		const started = performance.now();
		cache = fetch("/catalog/parts.json").then((res) => {
			if (!res.ok) throw new Error("Каталог не открылся");
			return res.json();
		}).then((data) => {
			return {
				parts: data.rows.map((row) => {
					const [id, name, brand, model, years, oem, engine, year, note, qty, price, stock, group, photos, repl] = row;
					return {
						id: String(id),
						name,
						brand,
						model,
						years,
						oem: oem || "",
						engine: engine || "",
						year: year || "",
						note: note || "",
						qty: Number(qty) || 1,
						price: Number(price) || 0,
						stock: stock === "main" ? "main" : "extra",
						group: group || "other",
						photos: photos ? String(photos).split("|").filter(Boolean).map((photo) => unpackPhoto(data.hosts, photo)) : [],
						repl: repl || "",
						supplier: catalogMeta.supplier,
						condition: "БУ"
					};
				}),
				ms: Math.round(performance.now() - started)
			};
		});
	}
	return cache;
}
function mergeParts(seed, imported) {
	if (!imported.length) return seed;
	const map = new Map(seed.map((part) => [part.id, part]));
	for (const part of imported) map.set(part.id, part);
	return [...map.values()];
}
function partPrice(part, global, profiles) {
	const profile = part.profileId ? profiles.find((item) => item.id === part.profileId) : void 0;
	return sellPrice(part.price, profile?.markup ?? global);
}
function norm(value) {
	return value.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}
function queryParts(parts, query, priceOf) {
	const tokens = norm(query.q || "").split(" ").filter(Boolean);
	let list = parts;
	if (query.brand) list = list.filter((part) => part.brand === query.brand);
	if (query.model) list = list.filter((part) => part.model === query.model && (!query.years || part.years === query.years));
	if (query.group) list = list.filter((part) => part.group === query.group);
	if (query.stock) list = list.filter((part) => part.stock === query.stock);
	if (tokens.length) list = list.filter((part) => {
		const hay = norm([
			part.name,
			part.brand,
			part.model,
			part.years,
			part.oem,
			part.id,
			part.engine,
			part.year,
			part.note,
			part.repl,
			part.supplier
		].join(" "));
		return tokens.every((token) => hay.includes(token));
	});
	const sorted = list.slice();
	const sort = query.sort || "price-asc";
	if (sort === "name") sorted.sort((a, b) => a.name.localeCompare(b.name, "ru"));
	else if (sort === "price-desc") sorted.sort((a, b) => priceOf(b) - priceOf(a) || a.name.localeCompare(b.name, "ru"));
	else sorted.sort((a, b) => priceOf(a) - priceOf(b) || a.name.localeCompare(b.name, "ru"));
	const pageSize = query.pageSize || 24;
	const pages = Math.max(1, Math.ceil(sorted.length / pageSize));
	const page = Math.min(Math.max(1, query.page || 1), pages);
	const start = (page - 1) * pageSize;
	return {
		total: sorted.length,
		page,
		pages,
		items: sorted.slice(start, start + pageSize)
	};
}
function suggestParts(parts, q, limit = 7) {
	const tokens = norm(q).split(" ").filter((token) => token.length > 1);
	if (!tokens.length) return [];
	const out = [];
	for (const part of parts) {
		const hay = norm(`${part.name} ${part.brand} ${part.model} ${part.oem} ${part.id}`);
		if (tokens.every((token) => hay.includes(token))) {
			out.push(part);
			if (out.length >= limit) break;
		}
	}
	return out;
}
function stockLabel(stock) {
	return stock === "main" ? "Основной склад" : "Под заказ";
}
function useCatalog() {
	const imports = useShop((state) => state.imports);
	const markup = useShop((state) => state.markup);
	const profiles = useShop((state) => state.profiles);
	const [seed, setSeed] = (0, import_react.useState)(null);
	const [ms, setMs] = (0, import_react.useState)(0);
	const [error, setError] = (0, import_react.useState)("");
	(0, import_react.useEffect)(() => {
		let alive = true;
		loadSeed().then((result) => {
			if (!alive) return;
			setSeed(result.parts);
			setMs(result.ms);
		}).catch((reason) => {
			if (!alive) return;
			setError(reason instanceof Error ? reason.message : "Каталог не открылся");
			setSeed([]);
		});
		return () => {
			alive = false;
		};
	}, []);
	return {
		parts: (0, import_react.useMemo)(() => seed ? mergeParts(seed, imports) : null, [seed, imports]),
		ms,
		error,
		priceOf: (0, import_react.useMemo)(() => (part) => partPrice(part, markup, profiles), [markup, profiles]),
		markup
	};
}
